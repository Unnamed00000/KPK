function getIsoWeek(date) {
  const utcDate = new Date(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()));
  const dayNumber = utcDate.getUTCDay() || 7;
  utcDate.setUTCDate(utcDate.getUTCDate() + 4 - dayNumber);
  const yearStart = new Date(Date.UTC(utcDate.getUTCFullYear(), 0, 1));
  return Math.ceil(((utcDate - yearStart) / 86400000 + 1) / 7);
}

function getWorkDayNumber(date) {
  const day = date.getDay();
  if (day >= 1 && day <= 5) {
    return String(day);
  }
  return "1";
}

function formatDateKey(date) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function parseDateKey(dateKey) {
  const [year, month, day] = dateKey.split("-").map(Number);
  return new Date(year, month - 1, day);
}

function getLocale() {
  return I18N[state.language]?.htmlLang || DEFAULT_LANGUAGE;
}

function getDateStorageKey(dateKey) {
  return `${STORAGE_PREFIX}${dateKey}`;
}

function readJsonStorage(key) {
  try {
    return JSON.parse(localStorage.getItem(key) || "{}");
  } catch {
    return {};
  }
}

function getSavedEntry(dateKey) {
  const saved = readJsonStorage(getDateStorageKey(dateKey));
  if (Object.keys(saved).length > 0) {
    return saved;
  }

  const todayKey = formatDateKey(new Date());
  if (dateKey === todayKey) {
    return readJsonStorage(LEGACY_STORAGE_KEY);
  }

  return {};
}

function getProfile() {
  return readJsonStorage(PROFILE_STORAGE_KEY);
}

function saveProfile(fullName, employeeNumber, defaultPlace) {
  localStorage.setItem(PROFILE_STORAGE_KEY, JSON.stringify({
    fullName,
    employeeNumber,
    defaultPlace
  }));
}

function hasSavedEntry(dateKey) {
  const saved = getSavedEntry(dateKey);
  return Boolean(
    saved.fullName
    || saved.employeeNumber
    || (Array.isArray(saved.rows) && saved.rows.length > 0)
  );
}

function formatDisplayDate(date) {
  return new Intl.DateTimeFormat(getLocale(), {
    weekday: "long",
    day: "numeric",
    month: "long",
    year: "numeric"
  }).format(date);
}

function t(key) {
  return I18N[state.language]?.[key] ?? I18N[DEFAULT_LANGUAGE][key] ?? key;
}

function getDayName(dayNumber) {
  return I18N[state.language]?.dayNames?.[dayNumber] ?? I18N[DEFAULT_LANGUAGE].dayNames[dayNumber];
}

