function addRow(values = {}) {
  const fragment = elements.rowTemplate.content.cloneNode(true);
  const rowElement = fragment.querySelector(".work-row");
  const pauseCount = state.rows.filter((item) => item.type === "pause").length;
  const defaultPause = DEFAULT_PAUSES[pauseCount] || DEFAULT_PAUSES[DEFAULT_PAUSES.length - 1];
  const row = {
    element: rowElement,
    place: rowElement.querySelector(".place-input"),
    series: rowElement.querySelector(".series-input"),
    start: rowElement.querySelector(".start-input"),
    end: rowElement.querySelector(".end-input"),
    duration: rowElement.querySelector(".duration-output"),
    moveUp: rowElement.querySelector(".move-up"),
    moveDown: rowElement.querySelector(".move-down"),
    remove: rowElement.querySelector(".remove-button"),
    type: values.type ?? "work"
  };

  row.place.value = values.place ?? (row.type === "pause" ? "-" : (row.type === "place" ? "" : getDefaultPlace()));
  row.series.value = row.type === "place" ? "" : (values.series ?? "");
  if (row.type === "pause") {
    row.start.value = parseTimeToMinutes(values.start) === null ? defaultPause.start : values.start;
    row.end.value = parseTimeToMinutes(values.end) === null ? defaultPause.end : values.end;
  } else {
    row.start.value = values.start ?? getNextStartTime();
    row.end.value = values.end ?? getShiftEnd();
  }

  applyRowType(row);
  attachRowEvents(row);
  state.rows.push(row);
  elements.rows.appendChild(rowElement);
  applyLanguageText(rowElement);
  updateTotals();
}

