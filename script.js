function copyPreview() {
  const text = getShareText();
  const markCopied = () => {
    elements.copyStatus.textContent = t("copied");
    window.setTimeout(() => {
      elements.copyStatus.textContent = "";
    }, 1800);
  };

  const fallbackCopy = () => {
    const textArea = document.createElement("textarea");
    textArea.value = text;
    textArea.style.position = "fixed";
    textArea.style.opacity = "0";
    document.body.appendChild(textArea);
    textArea.select();
    const copied = document.execCommand("copy");
    textArea.remove();
    return copied;
  };

  if (!navigator.clipboard) {
    if (fallbackCopy()) {
      markCopied();
    } else {
      elements.copyStatus.textContent = t("copyFailed");
    }
    return;
  }

  navigator.clipboard.writeText(text).then(markCopied).catch(() => {
    if (fallbackCopy()) {
      markCopied();
    } else {
      elements.copyStatus.textContent = t("copyFailed");
    }
  });
}

function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

async function sharePdf() {
  try {
    const pdfBlob = await createSharePdf();
    const filename = `kpk-${state.selectedDate || "arbejdsseddel"}.pdf`;
    const file = new File([pdfBlob], filename, { type: "application/pdf" });

    if (navigator.canShare?.({ files: [file] }) && navigator.share) {
      await navigator.share({
        title: "KPK",
        text: t("readyText"),
        files: [file]
      });
      return;
    }

    downloadBlob(pdfBlob, filename);
    elements.copyStatus.textContent = t("shareUnavailable");
    window.setTimeout(() => {
      elements.copyStatus.textContent = "";
    }, 2400);
  } catch {
    elements.copyStatus.textContent = t("shareFailed");
  }
}

