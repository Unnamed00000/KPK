function getWeekStart(date) {
  const result = new Date(date);
  const day = result.getDay() || 7;
  result.setDate(result.getDate() - day + 1);
  result.setHours(0, 0, 0, 0);
  return result;
}

function getCalendarStart(monthDate) {
  return getWeekStart(new Date(monthDate.getFullYear(), monthDate.getMonth(), 1));
}

function createCalendarCell(className, text) {
  const cell = document.createElement("div");
  cell.className = className;
  cell.textContent = text;
  return cell;
}

function renderCalendar() {
  if (!elements.calendarGrid || !elements.calendarTitle) {
    return;
  }

  const monthDate = state.calendarMonth;
  elements.calendarTitle.textContent = new Intl.DateTimeFormat(getLocale(), {
    month: "long",
    year: "numeric"
  }).format(monthDate);

  elements.calendarGrid.textContent = "";
  elements.calendarGrid.appendChild(createCalendarCell("calendar-weekday", t("week")));

  const monday = new Date(2026, 7, 3);
  for (let index = 0; index < 7; index += 1) {
    const day = new Date(monday);
    day.setDate(monday.getDate() + index);
    elements.calendarGrid.appendChild(createCalendarCell("calendar-weekday", new Intl.DateTimeFormat(getLocale(), {
      weekday: "short"
    }).format(day)));
  }

  const todayKey = formatDateKey(new Date());
  const calendarStart = getCalendarStart(monthDate);

  for (let week = 0; week < 6; week += 1) {
    const weekDate = new Date(calendarStart);
    weekDate.setDate(calendarStart.getDate() + week * 7);
    elements.calendarGrid.appendChild(createCalendarCell("calendar-week", getIsoWeek(weekDate)));

    for (let dayIndex = 0; dayIndex < 7; dayIndex += 1) {
      const date = new Date(weekDate);
      date.setDate(weekDate.getDate() + dayIndex);
      const dateKey = formatDateKey(date);
      const button = document.createElement("button");
      button.className = "calendar-day";
      button.type = "button";
      button.textContent = date.getDate();
      button.setAttribute("aria-label", formatDisplayDate(date));
      button.dataset.date = dateKey;

      if (date.getMonth() !== monthDate.getMonth()) {
        button.classList.add("is-outside");
      }
      if (dateKey === todayKey) {
        button.classList.add("is-today");
      }
      if (hasSavedEntry(dateKey)) {
        button.classList.add("has-entry");
      }

      button.addEventListener("click", () => openEditor(dateKey));
      elements.calendarGrid.appendChild(button);
    }
  }
}

function updateSelectedDateLabel() {
  if (!elements.selectedDateLabel || !state.selectedDate) {
    return;
  }

  const date = parseDateKey(state.selectedDate);
  elements.selectedDateLabel.textContent = `${formatDisplayDate(date)} · ${t("week")} ${getIsoWeek(date)}`;
}

