function parseTimeToMinutes(value) {
  if (!value) {
    return null;
  }
  const [hours, minutes] = value.split(":").map(Number);
  if (Number.isNaN(hours) || Number.isNaN(minutes)) {
    return null;
  }
  return hours * 60 + minutes;
}

function minutesToUnits(totalMinutes) {
  if (totalMinutes === 500) {
    return 832;
  }
  return Math.round((totalMinutes / 60) * 100);
}

function formatUnits(units) {
  const sign = units < 0 ? "-" : "";
  const absolute = Math.abs(units);
  const hours = Math.floor(absolute / 100);
  const hundredths = absolute % 100;
  return `${sign}${hours},${String(hundredths).padStart(2, "0")}`;
}

function getDurationMinutes(start, end) {
  const startMinutes = parseTimeToMinutes(start);
  const endMinutes = parseTimeToMinutes(end);
  if (startMinutes === null || endMinutes === null) {
    return 0;
  }
  let duration = endMinutes - startMinutes;
  if (duration < 0) {
    duration += 24 * 60;
  }
  return duration;
}

function getTimeWindow(start, end) {
  const startMinutes = parseTimeToMinutes(start);
  const endMinutes = parseTimeToMinutes(end);
  if (startMinutes === null || endMinutes === null) {
    return null;
  }

  return {
    start: startMinutes,
    end: endMinutes < startMinutes ? endMinutes + 24 * 60 : endMinutes
  };
}

function getPauseOverlapMinutes(start, end) {
  const rowWindow = getTimeWindow(start, end);
  if (!rowWindow) {
    return 0;
  }

  return DEFAULT_PAUSES.reduce((sum, pause) => {
    const pauseWindow = getTimeWindow(pause.start, pause.end);
    if (!pauseWindow) {
      return sum;
    }

    const overlapStart = Math.max(rowWindow.start, pauseWindow.start);
    const overlapEnd = Math.min(rowWindow.end, pauseWindow.end);
    return sum + Math.max(0, overlapEnd - overlapStart);
  }, 0);
}

function getWindowOverlapMinutes(rowWindow, excludeWindow) {
  if (!rowWindow || !excludeWindow) {
    return null;
  }

  const start = Math.max(rowWindow.start, excludeWindow.start);
  const end = Math.min(rowWindow.end, excludeWindow.end);
  if (end <= start) {
    return null;
  }

  return { start, end };
}

function getMergedOverlapMinutes(row, excludedWindows) {
  const rowWindow = getTimeWindow(row.start.value, row.end.value);
  if (!rowWindow) {
    return 0;
  }

  const overlaps = excludedWindows
    .map((window) => getWindowOverlapMinutes(rowWindow, window))
    .filter(Boolean)
    .sort((first, second) => first.start - second.start);

  if (overlaps.length === 0) {
    return 0;
  }

  const merged = [];
  overlaps.forEach((window) => {
    const previous = merged[merged.length - 1];
    if (!previous || window.start > previous.end) {
      merged.push({ ...window });
      return;
    }
    previous.end = Math.max(previous.end, window.end);
  });

  return merged.reduce((sum, window) => sum + window.end - window.start, 0);
}

function getDefaultPauseWindows() {
  return DEFAULT_PAUSES
    .map((pause) => getTimeWindow(pause.start, pause.end))
    .filter(Boolean);
}

function moveTimeAfterPause(value) {
  const minutes = parseTimeToMinutes(value);
  if (minutes === null) {
    return value;
  }

  const pause = DEFAULT_PAUSES.find((item) => {
    const start = parseTimeToMinutes(item.start);
    const end = parseTimeToMinutes(item.end);
    return start !== null && end !== null && minutes >= start && minutes < end;
  });

  return pause?.end || value;
}

