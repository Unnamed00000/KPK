function buildPreview(rowUnits, summary) {
  const totalUnits = minutesToUnits(summary.totalMinutes);
  const lines = [
    `${t("fullName")}: ${elements.firstName.value || "__________"}`,
    `${t("employeeNumber")}: ${elements.employeeNumber.value || "__________"} | ${t("week")}: ${elements.weekNumber.value || "__"} | ${t("day")}: ${elements.dayNumber.value} (${getDayName(elements.dayNumber.value)})`,
    `${t("shift")}: ${getShiftWindowText()}`,
    "",
    `${t("work")}:`
  ];

  const filledRows = state.rows.filter((row) => row.type !== "pause" && (row.place.value || row.series.value || row.start.value || row.end.value));
  if (filledRows.length === 0) {
    lines.push(t("noRows"));
  } else {
    filledRows.forEach((row, index) => {
      const rowIndex = state.rows.indexOf(row);
      const series = row.series.value || "__________";
      const place = row.place.value || (isPlaceOnlyRow(row) ? "__________" : getDefaultPlace());
      const start = row.start.value || "__:__";
      const end = row.end.value || "__:__";
      const rowParts = [`${index + 1}. ${place}`];

      if (isMeetingRow(row)) {
        rowParts.push(series);
      } else if (!isPlaceOnlyRow(row)) {
        rowParts.push(`${t("series")} ${series}`);
      }

      rowParts.push(`${start}-${end}`, formatUnits(rowUnits[rowIndex] || 0));
      lines.push(rowParts.join(" | "));
    });
  }

  lines.push("");
  lines.push(`${t("total")}: ${formatUnits(totalUnits)}`);

  return lines.join("\n");
}

