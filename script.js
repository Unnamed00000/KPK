async function forceRefreshApp() {
  setUpdateStatus(window.location.protocol === "file:" ? "forceRefreshLocal" : "forceRefreshStarted");
  if (elements.forceRefreshButton) {
    elements.forceRefreshButton.disabled = true;
  }
  try {
    if ("serviceWorker" in navigator) {
      const registrations = await navigator.serviceWorker.getRegistrations();
      await Promise.all(registrations.map((registration) => registration.update()));
    }

    if ("caches" in window) {
      const keys = await caches.keys();
      await Promise.all(keys.map((key) => caches.delete(key)));
    }

    if ("serviceWorker" in navigator) {
      const registrations = await navigator.serviceWorker.getRegistrations();
      await Promise.all(registrations.map((registration) => registration.unregister()));
    }
  } catch {
    // Force reload still continues if cache APIs are unavailable.
  }

  const url = new URL(window.location.href);
  url.searchParams.set("forceUpdate", String(Date.now()));
  window.setTimeout(() => {
    window.location.replace(url.toString());
  }, window.location.protocol === "file:" ? 900 : 150);
}

function playFeedback() {
  if (state.vibration && "vibrate" in navigator) {
    navigator.vibrate(25);
  }

  if (!state.sound) {
    return;
  }

  try {
    const AudioContext = window.AudioContext || window.webkitAudioContext;
    if (!AudioContext) {
      return;
    }
    const audioContext = new AudioContext();
    const oscillator = audioContext.createOscillator();
    const gain = audioContext.createGain();
    oscillator.type = "sine";
    oscillator.frequency.value = 560;
    gain.gain.value = 0.035;
    oscillator.connect(gain);
    gain.connect(audioContext.destination);
    oscillator.addEventListener("ended", () => {
      audioContext.close().catch(() => {});
    });
    oscillator.start();
    gain.gain.exponentialRampToValueAtTime(0.001, audioContext.currentTime + 0.11);
    oscillator.stop(audioContext.currentTime + 0.12);
  } catch {
    // Feedback is optional; older browsers can ignore it.
  }
}

function getSavedEntry(dateKey) {
  const saved = readJsonStorage(getDateStorageKey(dateKey));
  if (Object.keys(saved).length > 0) {
    return saved;
  }

  const todayKey = formatDateKey(new Date());
  if (dateKey === todayKey) {
    return readJsonStorage(LEGACY_STORAGE_KEY);
  }

  return {};
}

