function moveRow(row, direction) {
  const currentIndex = state.rows.indexOf(row);
  const nextIndex = currentIndex + direction;

  if (currentIndex === -1 || nextIndex < 0 || nextIndex >= state.rows.length) {
    return;
  }

  const otherRow = state.rows[nextIndex];
  state.rows[currentIndex] = otherRow;
  state.rows[nextIndex] = row;

  if (direction < 0) {
    elements.rows.insertBefore(row.element, otherRow.element);
  } else {
    elements.rows.insertBefore(otherRow.element, row.element);
  }

  updateTotals();
}

