function buildPreview(rowDetails, summary) {
  const totalUnits = minutesToUnits(summary.totalMinutes);
  const distributedUnits = distributeUnitsByMinutes(rowDetails, totalUnits);
  const lines = [
    `${t("fullName")}: ${elements.firstName.value || "__________"}`,
    `${t("employeeNumber")}: ${elements.employeeNumber.value || "__________"} | ${t("week")}: ${elements.weekNumber.value || "__"} | ${t("day")}: ${elements.dayNumber.value} (${getDayName(elements.dayNumber.value)})`,
    `${t("shift")}: ${getShiftWindowText()} | ${t("period")}: ${getWorkModeText()}`,
    "",
    `${t("work")}:`
  ];

  const filledRows = state.rows.filter((row) => row.type !== "pause" && (row.place.value || row.series.value || row.start.value || row.end.value));
  let totalLineIndent = 0;
  let finalSeparatorLength = 32;
  if (filledRows.length === 0) {
    lines.push(t("noRows"));
  } else {
    let lineNumber = 1;
    const workLines = [];
    const addWorkLine = (parts, duration) => {
      workLines.push({
        type: "row",
        prefix: parts.join(" | "),
        duration
      });
    };
    const addTotalLine = (duration) => {
      workLines.push({
        type: "total",
        prefix: t("total"),
        duration
      });
    };

    filledRows.forEach((row, index) => {
      const rowIndex = state.rows.indexOf(row);
      const detail = rowDetails[rowIndex];
      const series = row.series.value || "__________";
      const place = row.place.value || (isPlaceOnlyRow(row) ? "__________" : getDefaultPlace());
      const start = row.start.value || "__:__";
      const end = row.end.value || "__:__";
      const rowParts = [`${lineNumber}. ${place}`];
      lineNumber += 1;

      if (isSickRow(row)) {
        rowParts[0] = `${lineNumber - 1}. ${t("sick")}`;
      } else if (isTimeOffRow(row)) {
        rowParts[0] = `${lineNumber - 1}. ${t("timeOff")}`;
      } else if (isMeetingRow(row)) {
        rowParts.push(series);
      } else if (isPlaceOnlyRow(row)) {
        if (row.series.value) {
          rowParts.push(row.series.value);
        }
      } else if (!isPlaceOnlyRow(row)) {
        rowParts.push(`${t("series")} ${series}`);
      }

      const mainUnits = distributedUnits.rangeUnits[rowIndex]?.[0] || 0;
      const rowTotalUnits = distributedUnits.rowUnits[rowIndex] || 0;
      const hasExtraTimes = (row.extraTimes || []).length > 0;
      rowParts.push(`${start}-${end}`);
      addWorkLine(rowParts, formatUnits(hasExtraTimes ? mainUnits : rowTotalUnits));

      (row.extraTimes || []).forEach((item, itemIndex) => {
        const extraStart = item.start.value || "__:__";
        const extraEnd = item.end.value || "__:__";
        const extraUnits = distributedUnits.rangeUnits[rowIndex]?.[itemIndex + 1] || 0;
        const extraParts = [`${lineNumber}. ${place}`];
        lineNumber += 1;

        if (isSickRow(row)) {
          extraParts[0] = `${lineNumber - 1}. ${t("sick")}`;
        } else if (isMeetingRow(row)) {
          extraParts.push(series);
        } else if (isPlaceOnlyRow(row)) {
          if (row.series.value) {
            extraParts.push(row.series.value);
          }
        } else if (!isPlaceOnlyRow(row) && !isTimeOffRow(row)) {
          extraParts.push(`${t("series")} ${series}`);
        }

        extraParts.push(`${extraStart}-${extraEnd}`);
        addWorkLine(extraParts, formatUnits(extraUnits));
      });
      if (hasExtraTimes) {
        addTotalLine(formatUnits(rowTotalUnits));
      }
      if (index < filledRows.length - 1) {
        workLines.push({ type: "separator" });
      }
    });

    const durationColumn = Math.max(
      0,
      ...workLines
        .filter((line) => line.type === "row")
        .map((line) => line.prefix.length + 3)
    );
    totalLineIndent = Math.max(0, durationColumn - t("total").length - 3);
    const separatorLength = Math.max(32, durationColumn + 5);
    finalSeparatorLength = separatorLength;
    workLines.forEach((line) => {
      if (line.type === "separator") {
        lines.push("-".repeat(separatorLength));
        return;
      }

      if (line.type === "total") {
        const totalPrefix = line.prefix;
        const totalStart = Math.max(0, durationColumn - totalPrefix.length - 3);
        lines.push(`${" ".repeat(totalStart)}${totalPrefix} | ${line.duration}`);
        return;
      }

      const padding = Math.max(0, durationColumn - line.prefix.length - 3);
      lines.push(`${line.prefix}${" ".repeat(padding)} | ${line.duration}`);
    });
  }

  lines.push("");
  lines.push("_".repeat(finalSeparatorLength));
  lines.push(`${" ".repeat(totalLineIndent)}${t("total")} | ${formatUnits(totalUnits)}`);

  return lines.join("\n");
}

