function getSavedLatestEndMinutes(saved, fallbackMinutes = 0) {
  if (!Array.isArray(saved.rows)) {
    return fallbackMinutes;
  }

  return saved.rows
    .filter((row) => row?.type !== "pause" && row?.type !== "timeOff" && row?.type !== "sick")
    .flatMap((row) => [
      row.end,
      ...((Array.isArray(row.extraTimes) ? row.extraTimes : []).map((item) => item?.end))
    ])
    .map((value) => parseTimeToMinutes(value))
    .filter((minutes) => minutes !== null)
    .reduce((latest, minutes) => Math.max(latest, minutes), fallbackMinutes);
}

function getSavedRowCountedMinutes(row) {
  if (!row || row.type === "pause") {
    return 0;
  }
  const mainMinutes = Math.max(0, getDurationMinutes(row.start, row.end) - getPauseOverlapMinutes(row.start, row.end));
  const extraMinutes = (Array.isArray(row.extraTimes) ? row.extraTimes : []).reduce((sum, item) => (
    sum + Math.max(0, getDurationMinutes(item?.start, item?.end) - getPauseOverlapMinutes(item?.start, item?.end))
  ), 0);
  return mainMinutes + extraMinutes;
}

function isSavedMeetingRow(row) {
  return row?.type === "meeting" || String(row?.place || "").trim() === "114";
}

function getSavedRowRanges(row) {
  return [
    { start: row?.start, end: row?.end },
    ...((Array.isArray(row?.extraTimes) ? row.extraTimes : []).map((item) => ({
      start: item?.start,
      end: item?.end
    })))
  ];
}

function getSavedMeetingWindows(savedRows, exceptRow = null) {
  return savedRows
    .filter((row) => row !== exceptRow && isSavedMeetingRow(row))
    .flatMap((row) => getSavedRowRanges(row))
    .map((range) => getTimeWindow(range.start, range.end))
    .filter(Boolean);
}

function getSavedRangePieces(row, range, savedRows, countedWindows, extraExcludedWindows = []) {
  if (row?.type === "pause") {
    const pauseWindow = getTimeWindow(range.start, range.end);
    return pauseWindow ? [pauseWindow] : [];
  }

  const excludedWindows = getDefaultPauseWindows();
  if (!isSavedMeetingRow(row)) {
    excludedWindows.push(...getSavedMeetingWindows(savedRows, row));
  }
  excludedWindows.push(...extraExcludedWindows);
  excludedWindows.push(...countedWindows);

  return subtractWindows(getTimeWindow(range.start, range.end), excludedWindows);
}

function getSavedCountedMinutes(saved = {}, options = {}) {
  if (!Array.isArray(saved.rows)) {
    return 0;
  }

  const excludeTypes = new Set(options.excludeTypes || []);
  const extraExcludedTypes = new Set(options.extraExcludedTypes || []);
  const extraExcludedWindows = saved.rows
    .filter((row) => extraExcludedTypes.has(row?.type))
    .flatMap((row) => getSavedRowRanges(row))
    .map((range) => getTimeWindow(range.start, range.end))
    .filter(Boolean);
  const savedRows = saved.rows.filter((row) => row?.type !== "pause" && !excludeTypes.has(row?.type));
  const countedWindows = [];
  return savedRows.reduce((total, row) => {
    const rowMinutes = getSavedRowRanges(row).reduce((sum, range) => {
      const pieces = getSavedRangePieces(row, range, savedRows, countedWindows, extraExcludedWindows);
      if (row?.type !== "pause") {
        countedWindows.push(...pieces);
      }
      return sum + sumWindows(pieces);
    }, 0);
    return total + rowMinutes;
  }, 0);
}

function getSavedTotalCountedMinutes(saved = {}) {
  return getSavedCountedMinutes(saved);
}

function getSavedWorkedMinutesForExtra(saved = {}) {
  return getSavedCountedMinutes(saved, {
    excludeTypes: ["timeOff", "sick"],
    extraExcludedTypes: ["timeOff", "sick"]
  });
}

function getEntryWorkMode(dateKey, saved = getSavedEntry(dateKey)) {
  if (saved.workMode) {
    return normalizeWorkMode(saved.workMode);
  }

  const date = parseDateKey(dateKey);
  const dayNumber = saved.dayNumber || getWorkDayNumber(date);
  const normalEnd = parseTimeToMinutes(getNormalShiftEnd(dayNumber)) || 0;
  const latestEnd = getSavedLatestEndMinutes(saved, normalEnd);
  return latestEnd > normalEnd ? "variable" : "normal";
}

function formatDurationClock(totalMinutes) {
  const sign = totalMinutes < 0 ? "-" : "";
  const absolute = Math.abs(totalMinutes);
  const hours = Math.floor(absolute / 60);
  const minutes = absolute % 60;
  return `${sign}${hours}:${String(minutes).padStart(2, "0")}`;
}

function minutesToTimeValue(totalMinutes) {
  const dayMinutes = ((totalMinutes % (24 * 60)) + 24 * 60) % (24 * 60);
  const hours = Math.floor(dayMinutes / 60);
  const minutes = dayMinutes % 60;
  return `${String(hours).padStart(2, "0")}:${String(minutes).padStart(2, "0")}`;
}

function isDefaultPauseMinute(totalMinutes) {
  return DEFAULT_PAUSES.some((pause) => {
    const start = parseTimeToMinutes(pause.start);
    const end = parseTimeToMinutes(pause.end);
    return start !== null && end !== null && totalMinutes >= start && totalMinutes < end;
  });
}

function addCountedMinutesSkippingPauses(startValue, countedMinutes) {
  let cursor = parseTimeToMinutes(startValue);
  if (cursor === null || countedMinutes <= 0) {
    return startValue;
  }

  let remaining = countedMinutes;
  while (remaining > 0) {
    if (!isDefaultPauseMinute(cursor)) {
      remaining -= 1;
    }
    cursor += 1;
  }

  return minutesToTimeValue(cursor);
}

